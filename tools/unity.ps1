param(
    [ValidateSet('Generate','WorldPreview','Walkthrough','WalkthroughWindows','UnifiedWorld','UnifiedWorldWindows','NoviceVillage','NoviceVillageWindows','NoviceVillageWebGL','Windows','Android','LinuxServer')] [string]$Target = 'Generate',
    [string]$EditorPath = ''
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$gamePath = Join-Path $projectRoot 'apps/game'
# Same search as tools/verify-unity-graybox.ps1 (PR #41): -EditorPath, $env:UNITY_EDITOR, the shared D:\DevTools
# install, then the Unity Hub default, always for the pinned version.
$version = ((Get-Content -LiteralPath (Join-Path $gamePath 'ProjectSettings/ProjectVersion.txt') | Select-String '^m_EditorVersion:\s*(\S+)').Matches[0].Groups[1].Value)
$candidates = @($EditorPath, $env:UNITY_EDITOR,
    "D:\DevTools\Unity\$version\Editor\Unity.exe",
    (Join-Path $env:ProgramFiles "Unity\Hub\Editor\$version\Editor\Unity.exe")) | Where-Object { $_ }
$EditorPath = $candidates | Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1
if (-not $EditorPath) { throw "Unity $version not found. Tried: $($candidates -join '; ')" }
if ($Target -eq 'WalkthroughWindows' -or $Target -eq 'UnifiedWorldWindows' -or $Target -eq 'NoviceVillageWindows') {
    # Input backend changes made by scene generation take effect after an Editor restart.
    $prepass = if ($Target -eq 'WalkthroughWindows') { 'Walkthrough' } elseif ($Target -eq 'NoviceVillageWindows') { 'NoviceVillage' } else { 'UnifiedWorld' }
    & $PSCommandPath -Target $prepass -EditorPath $EditorPath
}
$methods = @{ Generate='Generate'; WorldPreview='Generate'; Walkthrough='Generate'; WalkthroughWindows='BuildWindows'; UnifiedWorld='Generate'; UnifiedWorldWindows='BuildWindows'; NoviceVillage='Generate'; NoviceVillageWindows='BuildWindows'; NoviceVillageWebGL='BuildWebGL'; Windows='BuildWindows'; Android='BuildAndroid'; LinuxServer='BuildLinuxServer' }
New-Item -ItemType Directory -Force -Path (Join-Path $projectRoot 'artifacts') | Out-Null
$log = Join-Path $projectRoot "artifacts/unity-$Target.log"
$builder = if ($Target -eq 'WorldPreview') { 'QingxiWorldBuilder' } elseif ($Target -like 'Walkthrough*') { 'QingxiWalkthroughBuilder' } elseif ($Target -like 'UnifiedWorld*') { 'QingxiUnifiedWorldBuilder' } elseif ($Target -like 'NoviceVillage*') { 'QingxiNoviceVillageBuilder' } else { 'ProjectBuilder' }
$method = 'YunJing.Editor.' + $builder + '.' + $methods[$Target]
$arguments = @('-batchmode','-nographics','-quit','-projectPath','.', '-executeMethod',$method,'-logFile',('"' + $log + '"'))
# The WebGL build reuses scenes generated by a NoviceVillage run; switching platform reimports assets once.
if ($Target -eq 'NoviceVillageWebGL') { $arguments += @('-buildTarget','WebGL') }
$process = Start-Process -FilePath $EditorPath -WorkingDirectory $gamePath -ArgumentList $arguments -WindowStyle Hidden -PassThru
# Wait for the Editor itself; helper processes may outlive a completed batch run.
$process.WaitForExit()
$process.Refresh()
if ($process.ExitCode -ne 0) { Get-Content -LiteralPath $log -Tail 35; throw "Unity failed ($($process.ExitCode)). Log: $log" }
Write-Host "Unity $Target completed. Log: $log"
